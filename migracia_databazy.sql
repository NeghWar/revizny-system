-- ============================================================
-- MIGRÁCIA DATABÁZY — Poznámka stroja + história porúch
-- Spusti v Supabase: Dashboard -> SQL Editor -> New query -> vlož -> RUN
-- ============================================================

-- 1) Doplň aktuálnu poznámku ku stroju (typ A: jedna poznámka na stroj)
alter table stroje add column if not exists poznamka text;
alter table stroje add column if not exists datum_poznamky date;

-- 1b) Doplň chýbajúce periódy (aplikácia ich očakáva podľa src/config.py)
alter table stroje add column if not exists interval_odborna_pr numeric;     -- float: 0.25 / 0.5 / 1 / 2 / 3
alter table stroje add column if not exists perioda_odbornej_skusky integer;  -- int (roky)

-- 2) Nová tabuľka: história porúch / poznámok
--    Sem sa automaticky zapíše stará poznámka pri prepise.
create table if not exists historia_poruch (
    id           bigint generated by default as identity primary key,
    datum_zapisu date not null default current_date,   -- kedy sa záznam zapísal
    nazov_stroja text not null,                        -- stroj (identifikácia, ktorý je pokazený)
    evidencne_cislo text,                              -- evidenčné číslo
    text_poruchy text not null                         -- text poruchy / poznámky
);

-- 3) (Voliteľné) index pre rýchlejšie filtrovanie histórie podľa stroja
create index if not exists idx_historia_poruch_stroj on historia_poruch (nazov_stroja);


-- ============================================================
-- ROČNÁ HISTÓRIA VYKONANÝCH PRÁC
-- Zaznamenáva, ktorá kontrola bola kedy vykonaná (pre ročný prehľad + Excel).
-- ============================================================
create table if not exists historia_rokov (
    id              bigint generated by default as identity primary key,
    rok             int  not null,                -- rok vykonania (pre rýchle filtrovanie)
    datum_vykonu    date not null,                -- dátum, kedy bola kontrola vykonaná
    nazov_stroja    text not null,                -- stroj
    evidencne_cislo text,                         -- evidenčné číslo
    voj             text,                         -- VOJ
    umiestnenie     text,                         -- umiestnenie
    typ_kontroly    text not null                 -- ktorá kontrola (napr. "Posledná Revízia")
);

create index if not exists idx_historia_rokov_rok on historia_rokov (rok);

